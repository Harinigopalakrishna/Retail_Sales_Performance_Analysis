CREATE DATABASE Capstone;
use Capstone;

-- 1. Create Tables Based on ERD 
-- o Use CREATE TABLE statements to replicate the exact structure of the ER diagram (with constraints).
CREATE TABLE Brands (
    Brand_id INT PRIMARY KEY,
    Brand_name VARCHAR(100) NOT NULL
);

CREATE TABLE Categories (
    Category_id INT PRIMARY KEY,
    Category_name VARCHAR(100) NOT NULL
);

CREATE TABLE Customers (
    Customer_id INT PRIMARY KEY,
    First_name VARCHAR(50) NOT NULL,
    Last_name VARCHAR(50) NOT NULL,
    Phone VARCHAR(25),
    Email VARCHAR(100),
    Street VARCHAR(100),
    City VARCHAR(50),
    State VARCHAR(50),
    Zip_code VARCHAR(10)
);

CREATE TABLE Stores (
    Store_id INT PRIMARY KEY,
    Store_name VARCHAR(100) NOT NULL,
    Phone VARCHAR(25),
    Email VARCHAR(100),
    Street VARCHAR(100),
    City VARCHAR(50),
    State VARCHAR(50),
    Zip_code VARCHAR(10)
);

CREATE TABLE Staffs (
    Staff_id INT PRIMARY KEY,
    First_name VARCHAR(50) NOT NULL,
    Last_name VARCHAR(50) NOT NULL,
    Email VARCHAR(100) NOT NULL,
    Phone VARCHAR(25),
    Store_id INT NOT NULL,
    Manager_id INT, CONSTRAINT FOREIGN KEY (Store_id) REFERENCES Stores(Store_id),
    CONSTRAINT FOREIGN KEY (Manager_id) REFERENCES Staffs(Staff_id)
);

CREATE TABLE Products (
    Product_id INT PRIMARY KEY,
    Product_name VARCHAR(255) NOT NULL,
    Brand_id INT NOT NULL,
    Category_id INT NOT NULL,
    Model_year YEAR NOT NULL,
    List_price DECIMAL(10,2) NOT NULL, CONSTRAINT FOREIGN KEY (Brand_id) REFERENCES Brands(Brand_id), 
    CONSTRAINT FOREIGN KEY (Category_id) REFERENCES Categories(Category_id)
);

CREATE TABLE Orders (
    order_id INT PRIMARY KEY,
    Customer_id INT NOT NULL,
    Order_status INT NOT NULL,
    Order_Status2 VARCHAR(50),
    Order_date DATE NOT NULL,
    Required_date DATE NOT NULL,
    Shipped_date DATE,
    Store_id INT NOT NULL,
    Staff_id INT NOT NULL, 
    CONSTRAINT FOREIGN KEY (Customer_id) REFERENCES Customers(Customer_id),
    CONSTRAINT FOREIGN KEY (Store_id) REFERENCES Stores(Store_id),
    CONSTRAINT FOREIGN KEY (Staff_id) REFERENCES Staffs(Staff_id)
);

CREATE TABLE Order_items (
    Order_ID INT NOT NULL,
    Item_ID INT NOT NULL,
    Product_ID INT NOT NULL,
    Product_Name VARCHAR(255),
    Quantity INT NOT NULL,
    List_Price DECIMAL(10,2) NOT NULL,
    Discount DECIMAL(4,2) NOT NULL, 
    Total_Sales DECIMAL(12,2),
    PRIMARY KEY (order_id, item_id),
    CONSTRAINT FOREIGN KEY (order_id) REFERENCES Orders(order_id),
    CONSTRAINT FOREIGN KEY (product_id) REFERENCES Products(Product_id)
);

SELECT * from Order_items;

CREATE TABLE Stocks (
    Store_id INT NOT NULL,
    Product_id INT NOT NULL,
    Quantity INT NOT NULL,
    PRIMARY KEY (Store_id, Product_id),
    CONSTRAINT FOREIGN KEY (Store_id) REFERENCES Stores(Store_id),
    CONSTRAINT FOREIGN KEY (Product_id) REFERENCES Products(Product_id)
);


-- 3. Inner Join for Order Details 
-- o Join orders, order_items, and products to display detailed line items. 

SELECT o.order_id,o.Order_date,oi.Product_id,p.Product_Name,oi.Quantity, oi.List_Price,oi.Total_Sales
FROM orders o
INNER JOIN order_items oi
ON o.order_id = oi.Order_ID
INNER JOIN products p
    ON oi.Product_ID = p.Product_id;

-- 4. Total Sales by Store 
-- o Write a query to group sales (total_price) by each store_id.

SELECT o.Store_id, SUM(oi.Total_Sales) AS total_sales
FROM orders o
INNER JOIN order_items oi
ON o.order_id = oi.Order_ID GROUP BY o.Store_id;

-- 5. Top 5 Selling Products 
-- o Use ORDER BY and LIMIT to get the top 5 most sold products by quantity.

SELECT p.Product_id, p.Product_name, SUM(oi.Quantity) AS total_quantity_sold
FROM order_items oi
INNER JOIN products p ON oi.Product_ID = P.product_id
GROUP BY p.Product_id, p.Product_name
ORDER BY total_quantity_sold DESC LIMIT 5;

-- 6. Customer Purchase Summary 
-- o For each customer, return total orders placed, total items purchased, and total revenue.
SELECT o.Customer_id, COUNT(DISTINCT o.Order_id) AS total_orders, 
SUM(oi.Quantity) AS total_items_purchased,
SUM(oi.Quantity * oi.List_Price) AS total_revenue
FROM orders AS o 
INNER JOIN order_items AS oi ON o.Order_id = oi.Order_ID
GROUP BY o.Customer_id;

-- 7. Segment Customers by Total Spend 
-- o Write a query to classify customers into spending brackets (e.g., low, medium, high).
SELECT o.Customer_id, SUM(oi.Total_Sales) AS Total_Spend,
    CASE
        WHEN SUM(oi.Total_Sales) < 10000 THEN 'Low'
        WHEN SUM(oi.Total_Sales) BETWEEN 10000 AND 50000 THEN 'Medium'
        ELSE 'High'
    END AS spending_bracket
FROM orders o
INNER JOIN order_items oi 
ON o.order_id = oi.Order_ID
GROUP BY o.Customer_id;

-- 8. Staff Performance Analysis 
-- o Analyze total revenue generated by each staff member based on their 
-- handled orders. 
SELECT o.Staff_id, SUM(oi.total_sales) AS total_revenue
FROM orders o
INNER JOIN order_items oi
ON o.order_id = oi.Order_ID
GROUP BY o.Staff_id
ORDER BY total_revenue DESC;

